from uuid import UUID

from rest_framework.permissions import IsAuthenticated
from rest_framework.request import Request

from accounts.views.base import CsrfProtectedView
from common.response.domain import (
    BaseResponse,
    ResourceUpdatedResponse,
    SuccessResponse,
)
from common.throttling.scoped import UserThrottle
from projects.constants import messages
from projects.responses import MemberGrantsData, RegistryData
from projects.serializers.permission import GrantReplaceSerializer
from projects.services import access, grant_service
from projects.views.base import ip_of


class PermissionRegistryView(CsrfProtectedView):
    """GET /api/permissions/: the registry, generated by the backend."""

    permission_classes = [IsAuthenticated]
    throttle_classes = [UserThrottle]

    def get(self, request: Request) -> BaseResponse:
        return SuccessResponse(data=RegistryData())


class MemberPermissionsView(CsrfProtectedView):
    def get(self, request: Request, project_id: UUID, user_id: UUID) -> BaseResponse:
        actor = access.get_membership(request.user, project_id)
        member, codes = grant_service.read(actor, user_id)
        return SuccessResponse(data=MemberGrantsData(member, codes))

    def put(self, request: Request, project_id: UUID, user_id: UUID) -> BaseResponse:
        data = GrantReplaceSerializer.parse(request.data)
        actor = access.get_membership(request.user, project_id)
        wanted = grant_service.resolve(data.get("permissions"), data.get("preset"))
        member, codes = grant_service.replace(actor, user_id, wanted, ip_of(request))
        return ResourceUpdatedResponse(
            data=MemberGrantsData(member, codes), message=messages.PERMISSIONS_UPDATED
        )
